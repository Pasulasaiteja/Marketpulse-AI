def normalize_currency(val: str | None) -> str | None:
    if not val:
        return None
    val_clean = str(val).strip()
    if val_clean in CURRENCY_MAP:
        return CURRENCY_MAP[val_clean]
    upper = val_clean.upper()
    if upper in CURRENCY_MAP:
        return CURRENCY_MAP[upper]
    if re.fullmatch(r"^[A-Za-z]{3}$", val_clean):
        return upper
    return upper


def normalize_country(val: str | None) -> str | None:
    if not val:
        return None
    val_clean = str(val).strip()
    if val_clean in COUNTRY_MAP:
        return COUNTRY_MAP[val_clean]
    upper = val_clean.upper()
    if upper in COUNTRY_MAP:
        return COUNTRY_MAP[upper]
    if re.fullmatch(r"^[A-Za-z]{2}$", val_clean):
        return upper
    return upper
